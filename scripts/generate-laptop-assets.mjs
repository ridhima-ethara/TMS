// Regenerates lib/constants/laptop-assets.js from the vendor inventory CSVs in
// scripts/data/. Run after updating the CSVs:
//   node scripts/generate-laptop-assets.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

const NON_CODES = new Set(["", "INTERN", "INTERM", "INTEN", "CONSULTANT"]);

function parseCsv(file, { platform, brandIndex, serialIndex, nameIndex, codeIndex, emailIndex, vendorIndex }) {
  const lines = readFileSync(join(root, "scripts/data", file), "utf8")
    .split(/\r?\n/)
    .slice(1)
    .filter((line) => line.trim());
  return lines.map((line) => {
    const cells = line.split(",").map((cell) => cell.trim());
    const rawCode = (cells[codeIndex] || "").toUpperCase().replace(/\s+/g, "");
    return {
      serial_number: (cells[serialIndex] || "").toUpperCase(),
      brand: cells[brandIndex] || "",
      name: (cells[nameIndex] || "").replace(/[^\x20-\x7E]/g, "").trim(),
      employee_code: NON_CODES.has(rawCode) ? "" : rawCode,
      email: (cells[emailIndex] || "").toLowerCase(),
      vendor: cells[vendorIndex] || "",
      platform,
    };
  });
}

const rows = [
  ...parseCsv("laptop-inventory-mac.csv", {
    platform: "Mac",
    brandIndex: 2,
    serialIndex: 3,
    nameIndex: 4,
    codeIndex: 1,
    emailIndex: 5,
    vendorIndex: 6,
  }),
  ...parseCsv("laptop-inventory-windows.csv", {
    platform: "Windows",
    brandIndex: 1,
    serialIndex: 2,
    nameIndex: 3,
    codeIndex: 4,
    emailIndex: 5,
    vendorIndex: 6,
  }),
];

const bySerial = new Map();
for (const row of rows) {
  if (!row.serial_number || !row.vendor) continue;
  if (!bySerial.has(row.serial_number)) bySerial.set(row.serial_number, row);
}
const assets = [...bySerial.values()];

const output = `// Laptop asset inventory bundled from the vendor sheets in scripts/data/.
// Generated by scripts/generate-laptop-assets.mjs — do not edit by hand.
export const LAPTOP_ASSETS = ${JSON.stringify(assets, null, 2)};
`;

writeFileSync(join(root, "lib/constants/laptop-assets.js"), output);
console.log(`Wrote ${assets.length} laptop assets (${rows.length} rows read).`);
